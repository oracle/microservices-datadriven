-- Clean-slate support-ticket schema.
create table support_ticket (
    id           number generated by default as identity primary key,
    title        varchar2(255) not null,
    description  varchar2(2000) not null,
    review_feedback clob,
    workflow_status varchar2(32) default 'RECEIVED' not null
        check (workflow_status in ('RECEIVED', 'TRIAGED', 'ENRICHED', 'FAILED')),
    embedding    vector(1536, FLOAT32)
);

-- Join table for related tickets
create table related_ticket (
    ticket_id       number not null,
    related         number not null,
    score           number(6,5) not null,
    constraint pk_support_ticket_relation primary key (ticket_id, related),
    constraint fk_ticket_id foreign key (ticket_id)
     references support_ticket(id) on delete cascade
);

-- Small illustrative policy corpus. The ai profile embeds missing vectors at startup.
create table support_policy (
    policy_id       varchar2(64) primary key,
    title           varchar2(255) not null,
    body            varchar2(2000) not null,
    embedding       vector(1536, FLOAT32)
);

insert into support_policy (policy_id, title, body) values (
    'ACCOUNT_ACCESS', 'Account access and password reset',
    'Verify the requester identity before resetting a password. Revoke compromised sessions and direct the user through the approved password reset flow.'
);
insert into support_policy (policy_id, title, body) values (
    'MFA_RECOVERY', 'Multi-factor authentication recovery',
    'Use the approved identity verification and MFA recovery process when a user loses an authenticator. Do not bypass MFA based only on a support request.'
);
insert into support_policy (policy_id, title, body) values (
    'BILLING_DISPUTE', 'Billing dispute review',
    'Capture the invoice identifier and disputed charge. Route the dispute for human review before issuing a refund or changing payment details.'
);

create table ticket_assistance (
    ticket_id       number primary key,
    summary         clob not null,
    summary_model   varchar2(256) not null,
    prompt_version  varchar2(64) not null,
    generated_at    timestamp with time zone default systimestamp not null,
    constraint fk_assistance_ticket foreign key (ticket_id)
        references support_ticket(id) on delete cascade
);

create table ticket_policy_match (
    ticket_id       number not null,
    policy_id       varchar2(64) not null,
    score           number(6,5) not null,
    constraint pk_ticket_policy_match primary key (ticket_id, policy_id),
    constraint fk_policy_match_ticket foreign key (ticket_id)
        references support_ticket(id) on delete cascade,
    constraint fk_policy_match_policy foreign key (policy_id)
        references support_policy(policy_id)
);

-- Durable idempotency and failed-event state for TxEventQ work.
create table ticket_event_processed (
    event_id       raw(16) primary key,
    ticket_id      number,
    processed_at   timestamp with time zone default systimestamp not null
);

create table failed_ticket_event (
    event_id        raw(16) primary key,
    schema_version number not null,
    ticket_id       number,
    event_type      varchar2(64),
    correlation_id  raw(16),
    causation_id    raw(16),
    attempt_count   number not null,
    failure_type    varchar2(256) not null,
    status          varchar2(16) not null
        check (status in ('FAILED', 'REPLAYED')),
    failed_at       timestamp with time zone default systimestamp not null
);

create index failed_ticket_event_status_idx on failed_ticket_event (status, failed_at);

-- Approval history for a fresh lab database.
-- Zero-day table retention permits deliberate lab cleanup; row retention is 16 days.
create blockchain table ticket_approval_history (
    action_id       raw(16) primary key,
    ticket_id       number not null,
    decision        varchar2(16) not null check (decision in ('APPROVED', 'REJECTED')),
    actor_id        varchar2(128 char) not null,
    reason          varchar2(1000 char),
    reviewed_summary clob not null,
    summary_digest  varchar2(64) not null,
    summary_model   varchar2(256) not null,
    prompt_version  varchar2(64) not null,
    decided_at      timestamp default sys_extract_utc(systimestamp) not null,
    constraint fk_approval_ticket foreign key (ticket_id) references support_ticket(id)
)
no drop until 0 days idle
no delete until 16 days after insert
hashing using "SHA2_512" version "v2";

create index ticket_approval_ticket_idx on ticket_approval_history(ticket_id, decided_at);

host touch /tmp/lab-schema-ready
prompt Lab schema is ready.
exit
